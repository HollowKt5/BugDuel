using UnityEngine;

namespace BeetleArena
{
    // Match phases: countdown warmup, active combat, double ring-out grace resolution, and match completion.
    public enum MatchPhase
    {
        Countdown,
        Fighting,
        Resolving,
        Finished
    }

    public enum BeetleResultReason
    {
        None,
        RingOut,
        TimeLimit,
        UnableToRight
    }

    // Action state of an individual beetle. Windup is preparatory, Pry is lifting, Toss is successful heave, Launched is airborne flight.
    // Future enum values append to the end to prevent legacy serialized integers from mapping to incorrect actions.
    public enum BeetleAction
    {
        Assess,
        Approach,
        Circle,
        ShoveWindup,
        Shove,
        PryWindup,
        Pry,
        Brace,
        Recover,
        Retreat,
        Stagger,
        Falling,
        Defeated,
        Winner,
        Probe,
        Disengage,
        ChargeWindup,
        Charge,
        HornLock,
        Toss,
        Launched,
        Lifting,
        Lifted,
        ReleaseLift,
        Module,
        Subdued
    }

    // Short-cycle bout pacing, decoupled from MatchPhase match flow and BeetleAction tactical state.
    public enum ExchangePhase
    {
        Probing,
        Clash,
        Recovery
    }

    // Complete dynamic data for a single fighter. Written by Simulation, read by Actor/Animator/HUD; free of scene dependencies.
    public sealed class BeetleState
    {
        // Fixed contestant index (0 for Amber, 1 for Obsidian). Traits reference remains immutable throughout the match.
        public readonly int Index;
        public readonly BeetleTraits Traits;
        public BeetleMatchEntrant Entrant { get; internal set; }
        public float VisualScale(BeetleMatchSettings settings) => Entrant?.VisualScale ?? settings.visualScale;
        // Position and Velocity represent world XZ plane coordinates and velocity in meters/sec; Vector2.y maps to world Z.
        public Vector2 Position, Velocity;
        // Heading is in degrees; Height is root world Y, accommodating uneven arena terrain rather than assuming a shared Y=0.
        public float Heading, Height, VerticalVelocity;
        public readonly BeetleLiftResponse Lift = new BeetleLiftResponse();
        public readonly BeetleFallResponse Fall = new BeetleFallResponse();
        public readonly BeetleMotionRuntime Motion = new BeetleMotionRuntime();
        // SurfaceHeight and Normal define current supporting ground; LastSupportHeight determines relative drop upon edge departure.
        public float SurfaceHeight, LastSupportHeight, SurfaceGrip = 1;
        public Vector3 SurfaceNormal = Vector3.up;
        public bool HasGround = true;
        // Stamina tracks current energy points; accumulated Fatigue depresses the recoverable ceiling.
        // Balance denotes postural stability, Footing denotes nominal grounding fraction of the six tarsi (both 0..1).
        public float Stamina, Fatigue, Balance = 1, Footing = 1;
        // BurstReserve is 0..1 short-term burst capacity; unlike recoverable stamina, it is not a secondary health bar.
        // Advantage and contact memory only bias decision-making, never serving as artificial damage multipliers. Simulation is sole writer.
        public float BurstReserve = 1, ExertionCooldown, ExposureRemaining, ContactConfidence;
        public float TacticalAdvantage, IntentTime;
        public System.Random DecisionRandom;
        public ExchangePhase CombatPhase = ExchangePhase.Probing;
        public float BoutTime, BoutDuration = 2, TimeSinceAttack;
        public float ContactReleaseRemaining, ContactReleaseCooldown;
        // Cooldown following inability to find a leverage pivot; allows short pushes or angle changes without repeating expensive failures.
        public float PryRetryRemaining;
        public BeetleIntent Intent = BeetleIntent.Assess;
        // Encouragement active duration and button cooldown are maintained separately; buff expiration does not imply instant availability.
        public float CheerRemaining, CheerCooldown;
        // Bilateral throw cooldown: granted to both attacker and defender following a throw, preventing instant ping-pong tosses.
        public float TossCooldown;
        // Attacker head pitch driver, generated by Simulation from defender's lift phase and consumed strictly by animation.
        public float LiftStrokeProgress, LiftSweepTarget;
        public int Throws; // Total prying throws; Tosses continues to track explosive throws for backwards metrics compatibility.
        public BeetleAction Action = BeetleAction.Assess;
        // ActionTime and ActionDuration represent progression in seconds; DecisionTime gates frequency of early tactical re-evaluation.
        public float ActionTime, ActionDuration = 1, DecisionTime;
        // Recovery timer persists across Recover/Retreat re-selection to prevent infinite chaining of brief actions; Simulation is sole writer.
        public float RecoveryTime, RecoveryCooldown;
        // Accepted contact geometry, sampled by the articulated solver. Render never writes these.
        public bool IsOverturned, RightingGrounded, RightingStable;
        public float OverturnedSeconds, RightingStableSeconds;
        public Vector3 RightingTorque;
        public int RightingSupports;
        // Landing friction is armed by a descending ground contact, never by time in flight.
        public bool LandingSliding;
        // Preserve the impact speed when the support-height fallback clears vertical velocity.
        public float LandingImpactSpeed;
        // Lift, lean, and impact presentation weights/angles decaying over simulation time; distinct from actual physical height or forces.
        public float LiftVisual, RollVisual, ImpactVisual;
        // Metrics for resolved hits, pushes, lifts, probes, charges, clinches, successful tosses, and eligible throw setups.
        // Contacts increments on both fighters once per contact event, not per-frame collision count (the latter tracked by ContactSolver.ContactFrames).
        public int Contacts, Shoves, Pries, ProbeTouches, Charges, Locks, Tosses, TossOpportunities;
        // Outgoing accepted-contact telemetry only; never used to choose a winner.
        public float AttackScore;
        public int ForelegActions, ForelegHits, ConsecutiveHornActions;
        public int FailedAttacks;
        // Airborne determines gravity application and suspends ground tactics; HasFallen is an irreversible ring-out flag.
        // AttackApplied guarantees each offensive action resolves impact effects exactly once.
        public bool Airborne, HasFallen, AttackApplied;
        // Whether the scene contact solver detected and resolved mutual overlap on the previous step, gating subsequent hit conditions.
        public bool TouchingOpponent;
        // Duration of continuous obstruction reported by the contact solver; Simulation abandons stalled actions without bypassing collisions.
        public float ContactBlockedSeconds;
        // Invariant circling bias (-1 or +1), also utilized for visual lean roll direction.
        public float CircleDirection;
        // Normalizes current action elapsed time to 0..1, safeguarding against division by near-zero durations.
        public float ActionProgress => Mathf.Clamp01(ActionTime / Mathf.Max(.001f, ActionDuration));
        // Each point of fatigue reduces maximum recoverable stamina by 0.7% of base stamina; clamped to 100.
        public float StaminaLimit => Traits.endurance * (1 - .007f * Fatigue);
        // Stamina fraction uses base stamina as denominator, so high fatigue can display below 100% even when fully recharged.
        public float Stamina01 => Mathf.Clamp01(Stamina / Traits.endurance);
        // Tactical decision-making uses current recoverable ceiling; actual output reads Stamina01, preventing fatigue from being bypassed.
        public float Readiness01 => Mathf.Clamp01(Stamina / Mathf.Max(.001f, StaminaLimit));
        // Converts yaw angle into forward vector on world plane: 0° points along +Z, 90° points along +X.
        public Vector2 Forward => new Vector2(Mathf.Sin(Heading * Mathf.Deg2Rad), Mathf.Cos(Heading * Mathf.Deg2Rad));
        // Set of actions actively charging, exerting force, or clinching; limits turning, controls gait, and accumulates fatigue.
        public bool Committed => Action == BeetleAction.Module || Action == BeetleAction.ShoveWindup || Action ==
            BeetleAction.Shove || Action == BeetleAction.PryWindup || Action == BeetleAction.Pry || Action ==
            BeetleAction.ChargeWindup || Action == BeetleAction.Charge || Action == BeetleAction.HornLock || Action ==
            BeetleAction.Toss || Action == BeetleAction.Lifting || Action == BeetleAction.ReleaseLift;
        // Initializes identity, stance, and stamina; other fields rely on declaration defaults, creating fresh state per match.
        public BeetleState(int index, BeetleTraits traits, Vector2 position, float heading)
        {
            Index = index;
            Traits = traits;
            Position = position;
            Heading = heading;
            Stamina = traits.endurance;
        }
    }

    // Lightweight event snapshot: Message for HUD, Actor index (-1 for global), Intensity hint for presentation; collision audio driven by contact sampling.
    public readonly struct ContestEvent
    {
        public readonly string Message;
        public readonly int Actor;
        public readonly float Intensity;
        // Latches text and intensity at event construction time; subscribers must not mutate original events.
        public ContestEvent(string message, int actor = -1, float intensity = 0)
        {
            Message = message;
            Actor = actor;
            Intensity = intensity;
        }
    }
}
